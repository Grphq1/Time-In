export function randomKaomoji(maxLength?: number) {
  const candidates = maxLength === undefined
    ? allKaomoji
    : allKaomoji.filter(item => item.length <= maxLength)

  return candidates[Math.floor(Math.random() * candidates.length)] ?? ''
}
